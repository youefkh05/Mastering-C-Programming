#include "include/bitwise.h" // Rule 21.1

// Function to perform bitwise AND operation
int bitwise_and(int a, int b) { return a & b; }

// Function to perform bitwise OR operation
int bitwise_or(int a, int b) { return a | b; }

// Function to perform bitwise XOR operation
int bitwise_xor(int a, int b) { return a ^ b; }

// Function to perform left shift operation
int left_shift(int a, int positions) { return a << positions; }

// Function to perform right shift operation
int right_shift(int a, int positions) { return a >> positions; }